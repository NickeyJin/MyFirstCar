/*
 * app.h —— 应用层（上电自检 + PS2 手柄全向移动）
 *
 * main() 里只调用两个函数：
 *     app_init();               // 初始化一次
 *     while (1) app_task();     // 主循环里反复调，内部自己按 20ms 节拍跑
 *
 * 操作方式（麦轮 3 自由度全开）：
 *     左摇杆   = 平移。推哪个方向车就往哪个方向走，斜推就斜着走，左右推就横移。
 *     右摇杆左右 = 原地自转（左推 = 左转）。
 *     按住 L1  = 慢速档（对位、贴近目标的时候用）。
 *     START    = 急停（按住就停）。
 */
#ifndef APP_H
#define APP_H

/* 上电自检开关：1 = 上电先依次点动四个轮子、整体前后走、横移一步，
 *                方便确认接线、转向和横移方向；
 *                调通之后改成 0 就直接进手柄控制 */
#define APP_SELFTEST_ENABLE   1

/* ===================== 电机排查模式 =====================
 * 1 = 上电后【不做自检、不进手柄控制】，而是无限循环做 3 组对比测试，
 *     专门用来定位"轮子完全不转"，把软件和硬件分开。
 *
 *     2026-10-11 实测结果：三段全转，且速度 闪3(1kHz/80%) > 闪2(100Hz/40%) > 闪1(20kHz/80%)。
 *       ⇒ 不是频率问题（20kHz 也能转），是占空比问题：这颗电机启动电压偏高，
 *         40% 带不动；同时驱动板有开关损耗，频率越高有效占空比越低。
 *       ⇒ 正式代码已改成 PSC=71 / ARR=999 → 1kHz，见 Core/Inc/motor.h 的 MOTOR_PWM_ARR。
 *     排查结束，这里已经改回 0。要再排查就改回 1。
 * ======================================================= */
#define APP_DIAG_MODE         0

/* ==================== 右后轮专项排查（APP_RR_TEST） ====================
 * 设成 1：上电后只驱动右后轮，循环跑 4 段，每段 3 秒，靠闪灯报段号。
 * 目的是把"右后轮往前不动"这件事拆成四段，一次定位是哪个环节断了：
 *
 *   闪 1 下 → PA11 当普通 GPIO 直接拉高（IN2=3.3V, IN1=0）  期望：前进
 *   闪 2 下 → PA8  当普通 GPIO 直接拉高（IN1=3.3V, IN2=0）  期望：后退
 *   闪 3 下 → PA11 走 TIM1_CH4 的 PWM（100%）               期望：前进
 *   闪 4 下 → PA8  走 TIM1_CH1 的 PWM（100%）               期望：后退
 *
 * 2026-10-11 实测：闪 1、闪 3 不动，闪 2、闪 4 正常转 ⇒ 问题在 PA11 这一侧
 * （或者是这个轮子只在"前进"这个机械方向上卡住 —— 两种现象一模一样，还没分开）。
 * PCB 已经画死 PA11 → DRV8833 IN2，没法改线，所以代码保持 PA11。
 * 详细读法和结论表写在 Core/Src/app.c 的 RR 排查段注释里。
 * 排查完把这里改回 0。注意：开着它的时候自检不会跑。
 * ======================================================= */
#define APP_RR_TEST           0

void app_init(void);
void app_task(void);

/* 主循环节拍，20ms = 50Hz，也是斜坡的最小时间粒度 */
#define APP_LOOP_MS           20

/* ===================== 速度相关 ===================== */

/* 快速档（默认）目标速度上限。<= CHASSIS_SPEED_MAX */
#define APP_SPEED_MAX         600

/* 慢速档（按住 L1）目标速度上限。
 * 注意：这颗电机 40% 上下才转得动，所以"慢"没法真的慢到爬；
 *       再往下调如果轮子不转或发抖，就把 APP_SPEED_MIN 一起调大。 */
#define APP_SPEED_SLOW        430

/* 起步补偿：摇杆一离开死区，速度就直接给到 APP_SPEED_MIN，而不是从 0 慢慢爬。
 * 因为实测这颗电机低占空比带不动，不加补偿的话摇杆前一半行程都是"死"的。
 * 嫌起步太猛地动可以调小；设成 0 就是关闭补偿。 */
#define APP_SPEED_MIN         350

/* 加减速斜坡：从 0 升到 APP_SPEED_MAX 大约要这么多毫秒。
 * 起步不冲、麦轮不打滑、驱动板电流也温和；嫌肉就调小，嫌冲就调大。 */
#define APP_RAMP_MS           300

/* 摇杆死区：手柄回中不会精确停在 0x80，留一点余量，顺手也规避手抖 */
#define APP_STICK_DEADZONE    12

#endif /* APP_H */
