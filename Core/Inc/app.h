/*
 * app.h —— 应用层（上电自检 + PS2 手柄全向移动）
 *
 * main() 里只调用两个函数：
 *     app_init();               // 初始化一次
 *     while (1) app_task();     // 主循环里反复调，内部自己按 20ms 节拍跑
 *
 * 操作方式（麦轮 3 自由度全开）：
 *     左摇杆     = 平移。推哪个方向车就往哪个方向走，斜推就斜着走，左右推就横移。
 *     右摇杆左右 = 原地自转（左推 = 左转）。
 *     按住 L1    = 慢速档（对位、贴近目标的时候用）。
 *     START      = 急停（按住就停）。
 *
 * 开发期排查代码（PWM 占空比对比测试、右后轮专项测试）已经挪到 Core/Src/diag.c，
 * 开关在 Core/Inc/diag.h 里，正常跑车时两个都是 0、不参与编译。
 */
#ifndef APP_H
#define APP_H

/* 上电自检开关：1 = 上电先依次点动四个轮子、整体前后走、横移一步，
 *                方便确认接线、转向和横移方向；
 *                调通之后改成 0 就直接进手柄控制 */
#define APP_SELFTEST_ENABLE   1

/* 主循环节拍，20ms = 50Hz，也是斜坡的最小时间粒度 */
#define APP_LOOP_MS           20

/* ===================== 速度相关 ===================== */

/* 快速档（默认）目标速度上限。<= CHASSIS_SPEED_MAX */
#define APP_SPEED_MAX         600

/* 慢速档（按住 L1）目标速度上限。
 * 注意：这颗电机 40% 上下才转得动，所以"慢"没法真的慢到爬；
 *       再往下调如果轮子不转或发抖，就把 APP_SPEED_MIN 一起调大。 */
#define APP_SPEED_SLOW        430

/* 起步补偿：摇杆一离开死区，速度就直接给到 APP_SPEED_MIN，而不是从 0 慢慢爬。
 * 因为实测这颗电机低占空比带不动，不加补偿的话摇杆前一半行程都是"死"的。
 * 嫌起步太猛地动可以调小；设成 0 就是关闭补偿。 */
#define APP_SPEED_MIN         350

/* 加减速斜坡：从 0 升到 APP_SPEED_MAX 大约要这么多毫秒。
 * 起步不冲、麦轮不打滑、驱动板电流也温和；嫌肉就调小，嫌冲就调大。 */
#define APP_RAMP_MS           300

/* 摇杆死区：手柄回中不会精确停在 0x80，留一点余量，顺手也规避手抖 */
#define APP_STICK_DEADZONE    12

void app_init(void);
void app_task(void);

#endif /* APP_H */
