/*
servo.h —— 3 路舵机 / 两级机械臂

硬件：PB6~PB8 = TIM4_CH1~CH3，PSC=71 / ARR=19999 → 50Hz，CCR 直接等于脉宽 µs
      （PB9 = TIM4_CH4 空出来备用）

★ 机构：两级
    一级 = 大臂            CH1 PB6  MG995
    二级 = 小臂 + 夹爪      CH2 PB7  肘（大臂/小臂连接处）**SG995**  ★ 2024 由 SG90 换
                           CH3 PB8  夹爪舵机 SG90

  "两级"的意思：肘关节只承担"小臂 + 夹爪"这一小段，不承担整条臂的重量。

  ★ 2024 改动：肘从 SG90（9g / 1.8 kg·cm）换成 **SG995**（55g / ~9 kg·cm）。
    原来那段"力矩校核"（60g/80g/100g 三档余量）**已经作废**，不再适用：

        旧：80g × 110mm = 0.88 kg·cm  vs  SG90 余量 2.0 倍  ⚠️ 偏紧
        新：同上        0.88 kg·cm  vs  SG995 余量 **~10 倍**  ✅ 绰绰有余

    但换来的代价要记住：
      · 肘舵机自重 9g → 55g（+46g），**这份重量加在大臂上**，大臂负载变重
      · 尺寸从 23×12×29mm 变成 **40×20×36mm**，**机构要重新设计，不是即插即换**
      · 堵转电流 0.7A → ~1.2A，**5V 供电要求提高**（见下面供电说明）

  ⚠️ 手册要求整车 180mm 自由落体 ×10 次。
     **SG995 是塑料齿**（MG995 才是金属齿），抗跌落和 SG90 一样弱。
     如果换大舵机是为了抗摔，应该换 **MG995**（同尺寸同价、金属齿、代码零改动）。

★★ 原来的"腕"关节取消了 —— 所以从 4 个舵机变成 3 个。
   顺带解决了一个老问题：旧机构要求小臂从 −93.7° 走到 167.7°（跨度 261°），
   180° 舵机物理上走不完。改成两级机构后这个跨度不复存在，**那个问题作废了**。

⚠️ 新机构的姿态角**全部需要重新标定**：旧尺寸总表里的角度是按 4 关节算的，已失效。
   两条标定路径：
     1. **示教录制**（teach.c）—— 人工操作一遍，按 START 回放  ← 推荐，见《示教录制与回放.md》
     2. 标定固件（CAR_SERVO_ONLY）—— 手柄点动，读出每个关节的角度
*/
#ifndef SERVO_H
#define SERVO_H

#include <stdint.h>

/* ---- 通道分配 ---------------------------------------------------------
 *   CH1 PB6  大臂    MG995    55g 标准舵机 / 金属齿 / ~9 kg·cm
 *   CH2 PB7  肘      SG995    55g 标准舵机 / 塑料齿 / ~9 kg·cm   ★ 原为 SG90
 *   CH3 PB8  夹爪    SG90      9g 小舵机   / 塑料齿 / ~1.8 kg·cm
 *   CH4 PB9  —— 空出来备用（双舵机夹爪的 B 通道也用这里）
 *
 * ⚠️ 驱动层完全通用：三者都是「50Hz PWM + 1~2ms 脉宽 = 0~180°」的标准模拟舵机，
 *    所以 write_ccr() / deg2us() 一行都不用改。
 *    型号差异只体现在【参数】上：脉宽端点、软限位、缓动速度、堵转电流。
 *
 * ⚠️ 换舵机（尤其换型号）后，**该通道必须重新标定脉宽端点**，否则会顶到机械限位。
 * ---------------------------------------------------------------------- */
#define CH_ARM      1   /* PB6 大臂  MG995 */
#define CH_ELBOW    2   /* PB7 肘    SG995 */
#define CH_GRIP     3   /* PB8 夹爪  SG90  */
#define CH_SPARE    4   /* PB9 空出（保留，不要占用）*/

#define SERVO_CH_COUNT  3   /* 现在只用 3 个舵机 */
#define SERVO_CH_MAX    4   /* TIM4 一共 4 路，内部数组按这个开 */

/* ---- 每通道脉宽标定 ----------------------------------------------------
 * ⚠️ 这些是"数据手册典型值"，**必须实测校正**。
 *    校正方法：用 CAR_SERVO_ONLY 标定固件，
 *              手柄把关节推到两个机械端点，看开始"嗡嗡"响的角度，
 *              再把不响的范围告诉我，我改这里。
 *
 * 本工程三个舵机（MG995 / SG995 / SG90）都按 1000~2000µs 走 0~180°。
 * 原代码写 500~2500 会顶到机械限位，所以先保守取 1000~2000。
 *
 * ⚠️ 换过舵机的通道必须【重新标定】：
 *     同型号不同批次的"0°/180°"对应脉宽可能差 50~100µs；
 *     换型号（肘：SG90 → SG995）差得更多。
 *     填错的后果：顶到机械限位 → 大舵机堵转发热 / 小舵机崩塑料齿。
 *
 * ★ 保留"每通道独立"的结构：以后某个关节点换成 270° 舵机、
 *   或者实测发现某通道脉宽范围不同，只改对应那一项即可。
 * ---------------------------------------------------------------------- */
#define SERVO_PULSE_MIN_180   1000
#define SERVO_PULSE_MAX_180   2000
#define SERVO_ANGLE_MAX_180    180

/* 兼容旧写法 */
#define SERVO_MIN       SERVO_PULSE_MIN_180
#define SERVO_MAX       SERVO_PULSE_MAX_180
#define SERVO_ANGLE_MAX SERVO_ANGLE_MAX_180

/* ---- 关节软限位（度，舵机角）------------------------------------------
 * ⚠️ 下面全是**占位值，不是实测值**。新机构装好后请用标定固件
 *    把每个关节慢慢点动到快要干涉的位置，再把限位收紧告诉我。
 *
 * 先取得比较保守（离两端各留 20~30°），这样第一次上电不会顶到机械限位。
 * ---------------------------------------------------------------------- */
#define ARM_MIN         20      /* CH1 大臂 */
#define ARM_MAX        160
#define ELBOW_MIN      10       /* CH2 肘（SG995，2024 由 SG90 换）*/
#define ELBOW_MAX     170

/* ⚠️ GRIP_OPEN / GRIP_CLOSE 不在这里定义 —— 它们必须等于 grip_set() 用的那套
 *    标定值，否则"姿态表"和"夹爪接口"会各自往夹爪通道写不同的角度，
 *    表现是夹着方块走到一半夹爪自己松开。见下面 SERVO_GRIP_* 之后那一段。 */

/* ==========================================================================
 * ★★ 夹爪结构：单舵机 + 齿轮齿条平行夹爪 + Fin Ray 柔性指 ★★
 *    （按机械组 3D 模型：中间一个齿轮装在舵机臂上，带动两条反向齿条，
 *      两根导轨保证平行，夹指内侧是 Fin Ray 弯曲细梁）
 * ==========================================================================
 * 统一用一个 0~100 的开合量控制：
 *       0   = 全开（张开到最大）
 *       100 = 全合（夹紧）
 *
 * 【为什么单舵机比双舵机好】
 *   齿轮齿条天然同步、自定心，不需要像双舵机那样做同步校准，
 *   也不会出现"一个快一个慢把夹爪扭歪"。少一个舵机、少一路电流、少一个 IO。
 *
 * 【模式选择】
 *   SERVO_GRIP_DUAL = 0  单舵机（当前结构，齿轮齿条）
 *   SERVO_GRIP_DUAL = 1  双舵机对开（如果以后改回两个舵机各驱动一指，用 CH3+CH4）
 *   也可以在 CMake 里传 -DSERVO_GRIP_DUAL=1 覆盖，不用改本文件。
 * -------------------------------------------------------------------------- */
#ifndef SERVO_GRIP_DUAL
#define SERVO_GRIP_DUAL   0
#endif

/* 单舵机模式：夹爪舵机接在哪个通道 */
#define SERVO_GRIP_CH          CH_GRIP    /* PB8 / TIM4_CH3 */
#define SERVO_GRIP_INVERT      0          /* 1 = 角度方向反过来（夹紧时角度变小）*/
#define SERVO_GRIP_ANGLE_OPEN   40        /* 全开时舵机角（度）*/
#define SERVO_GRIP_ANGLE_CLOSE 140        /* 全合时舵机角（度）*/

/* 双舵机模式（SERVO_GRIP_DUAL=1 时才用）：两指镜像安装，方向通常相反 */
#define SERVO_GRIP_A_CH        CH_GRIP    /* 夹爪舵机 A（PB8）*/
#define SERVO_GRIP_B_CH        CH_SPARE   /* 夹爪舵机 B（PB9）*/
#define SERVO_GRIP_A_INVERT    0
#define SERVO_GRIP_B_INVERT    1

/* ==========================================================================
 * 【装配后必须标定的三个数】
 * ==========================================================================
 * 1. SERVO_GRIP_CH —— 夹爪舵机实际接在哪个脚（现在是 PB8 = CH3）
 * 2. SERVO_GRIP_ANGLE_OPEN / _CLOSE —— 全开和全合的舵机角度
 *    标定方法：烧 CAR_SERVO_ONLY 固件，手柄 L1/R1 选到该通道，
 *              慢慢推到夹指完全张开记下角度，再推到完全合拢记下角度。
 *    ⚠️ 两边各留 5~10° 余量，别顶到机械限位（会一直嗡嗡响、发热、烧舵机）
 * 3. SERVO_GRIP_INVERT —— 如果"夹紧"对应角度**变小**，就设成 1
 *
 * 【行程校核（机械那边要确认）】
 *   行程 = 2 × 齿轮节圆半径 × (舵机转角 / 360)
 *   要夹 30mm 官方方块，夹指内间距张开至少要到 34~36mm。
 * ========================================================================== */

/* 双舵机模式下的端点角度（SERVO_GRIP_DUAL=1 时才用）*/
#define SERVO_GRIP_A_ANGLE_OPEN    30    /* A 全开角度 */
#define SERVO_GRIP_A_ANGLE_CLOSE  150    /* A 全合角度 */
#define SERVO_GRIP_B_ANGLE_OPEN   150    /* B 全开角度 */
#define SERVO_GRIP_B_ANGLE_CLOSE   30    /* B 全合角度 */

/* ==========================================================================
 * ★ GRIP_OPEN / GRIP_CLOSE：姿态表里夹爪用的那两个角度
 * ==========================================================================
 * 【为什么必须从这里派生，而不是随手写两个数】
 *   全工程对夹爪有两套写法：
 *     1. grip_set(pct)   —— 0~100 开合量（上层代码用的，标定值就是 SERVO_GRIP_*）
 *     2. Pose_t.grip     —— 姿态表里直接写的"舵机角度"（arm_goto_pose 用）
 *   两套写法最终都写夹爪通道的同一个 CCR。**如果它们不相等，就会打架**：
 *   动作序列里"摆姿态"和"动夹爪"交替出现，夹爪会在两步之间被拽到另一个角度，
 *   表现就是"夹着方块走到一半自己松了"。
 *
 *   所以这里把姿态表的两个角度**从 grip_set() 的标定值派生出来**，
 *   标定一次，两套写法同时生效。改 SERVO_GRIP_ANGLE_* 就是唯一的入口。
 * -------------------------------------------------------------------------- */
#if SERVO_GRIP_DUAL
/* 双舵机模式：姿态表里的夹爪指"夹爪 B"的角度 */
#define GRIP_OPEN      SERVO_GRIP_B_ANGLE_OPEN
#define GRIP_CLOSE     SERVO_GRIP_B_ANGLE_CLOSE
#else
/* 单舵机模式：姿态表里的夹爪就是唯一的夹爪舵机 */
#define GRIP_OPEN      SERVO_GRIP_ANGLE_OPEN       /* 张开角，== grip_set(0)   */
#define GRIP_CLOSE     SERVO_GRIP_ANGLE_CLOSE      /* 夹紧角，== grip_set(100) */
#endif

/* ---- 开合量（0~100）的具名常量，别再在代码里写裸数字 ------------------- */
#define GRIP_PCT_OPEN    0      /* 全开 */
#define GRIP_PCT_CLOSE 100      /* 全合（夹紧）*/
#define GRIP_PCT_HOLD   (-1)    /* 动作序列里表示"这一步不动夹爪" */

/* ---- 每个关节的缓动速度（度/秒）---------------------------------------
 * MG995 在 7.4V 下堵转电流可达 2A 以上。全部瞬时跳变会把 5V 拉垮，
 * 所以所有角度变化都按"度/秒"限速，由 50Hz 的 servo_poll() 推进。
 *
 * ⚠️ 注意 servo.c 里 step = 速度/50 是**整数除法**，只保留了标称值。
 *    90/50 = 1 → 实际 50°/s；150/50 = 3 → 实际 150°/s。
 *    想真的跑 90°/s 就把数值取成 50 的整数倍（见《舵机第5课》5.5 问题 4）。
 *
 * ---------------------------------------------------------------------------
 * ★ 供电要求（2024 肘换 SG995 后重新算过）
 *
 *   三个舵机的堵转电流：
 *       CH1 大臂 MG995   ~1.2 A
 *       CH2 肘   SG995   ~1.2 A   ← 原来是 SG90 的 ~0.7 A
 *       CH3 夹爪 SG90    ~0.7 A
 *       ─────────────────────────
 *       峰值合计         ~3.1 A   ← 原来是 ~2.6 A
 *
 *   ⇒ 5V 电源额定电流 **≥ 3A**（原设计 5A 够用），
 *     舵机插座旁那个 **1000µF 电解**不能省。
 *
 *   为什么强调电流：MG995/SG995 在启动和堵转瞬间电流是额定的好几倍，
 *   三个一起动会把 5V 拉垮 → 单片机复位 / 舵机乱抖。
 *   所以代码层也做了限速（缓动），就是为了避免"三个同时瞬时跳变"。
 * ---------------------------------------------------------------------- */
#define ARM_SPEED       90      /* 大臂：挂整条臂，最慢最稳 */
#define ELBOW_SPEED    150      /* 肘：SG995（2024 由 SG90 换）。SG995 约 353°/s，150 在能力内 */
#define GRIP_SPEED     180      /* 夹爪：最轻 */

/* ==========================================================================
 * ★★★ 标定姿态 —— 下面全是【占位值，必须重新标定】 ★★★
 * ==========================================================================
 * 为什么是占位值：机构从"4 关节（大臂/小臂/腕/夹指）"改成
 * "3 关节两级（大臂 / 肘 / 夹爪）"，旧尺寸总表的角度是按旧机构算的，
 * **用在新机构上可能直接把臂顶到机械限位上**。
 *
 * 所以这里先全部取 90°（中位）——中位离两端最远，上电就算跑过去也不会撞。
 *
 * 【怎么把真实值填进来】二选一：
 *   A. 示教录制（推荐，见 teach.h）：把动作录下来直接回放，
 *      **根本不需要这几个姿态角**（它们只影响"自动收回"和上面那个动作序列）。
 *   B. 标定固件：烧 build/ServoCalib，手柄把臂点动到想要的姿态，
 *      按 START 用 PC13 读出角度，填到下面。
 *
 * ⚠️ 在填好之前：**别按 △（收回）**，也别让上电缓动到 POSE_STOW
 *    （见下面 ARM_POWERON_TO_STOW，默认是 0 = 保持中位，最安全）。
 * ========================================================================== */
typedef struct {
    int16_t arm;
    int16_t elbow;
    int16_t grip;      /* 夹爪的"舵机角度"，不是开合量 */
} Pose_t;

extern const Pose_t POSE_STOW;    /* 收纳 / 运输（检录定妆、每局开局）← 自动收回的目标 */
extern const Pose_t POSE_GRAB;    /* 抓取（占位）*/
extern const Pose_t POSE_LIFT;    /* 抬起过渡（占位）*/
extern const Pose_t POSE_FEED;    /* 投料位置（占位）*/

/* ---- 上电时去哪 --------------------------------------------------------
 *   0 = 保持中位（90/90/90）★ 新机构第一次上电必须用这个
 *   1 = 缓动到 POSE_STOW（**只在 POSE_STOW 标定完之后**才改成 1）
 * ---------------------------------------------------------------------- */
#ifndef ARM_POWERON_TO_STOW
#define ARM_POWERON_TO_STOW   0
#endif

/* ---- 原始脉宽接口（保留，兼容旧调用）--------------------------------- */
void servo_set(uint8_t no, uint16_t us);
void servo_start(void);

/* ---- 标定专用接口（CAR_SERVO_ONLY 测试模式用）-------------------------
 * 标定时需要越过软限位去"探边界"，所以单独给一组能直接写脉宽/角度的接口。
 * ⚠️ 只在测试模式里用，正式跑车不要调。
 * ---------------------------------------------------------------------- */
void    servo_cal_pulse(uint8_t ch, uint16_t us);  /* 直接写脉宽 us */
void    servo_cal_angle(uint8_t ch, int16_t deg);  /* 直接写角度，跳过软限位 */
int16_t servo_cal_get(uint8_t ch);                 /* 当前角度 */

/* ---- 机械臂接口 ------------------------------------------------------- */
void    arm_init(void);                            /* 启动 PWM，并缓动到上电位置 */
void    arm_set_target(uint8_t ch, int16_t deg);   /* 设定目标角（度）*/
void    arm_set_target_raw(uint8_t ch, int16_t deg);/* 同上，跳过软限位 */
int16_t arm_get_angle(uint8_t ch);                 /* 当前角（缓动中的实时值）*/
int16_t arm_get_target(uint8_t ch);                /* 目标角 */
uint8_t arm_is_moving(void);                       /* 还有关节在动 → 1 */

/* 在当前位置基础上增减角度（手柄微调用）*/
void    arm_jog(uint8_t ch, int16_t delta);

void    arm_goto_pose(const Pose_t *p);            /* 缓动到姿态 */

/* ★ 自动收回：缓动回收纳姿态（stow）。
 *   回放结束后会自动调它（见 teach.c 的 TEACH_AUTO_STOW），手柄 △ 也绑它。
 *   ⚠️ 目标姿态默认就是 POSE_STOW（占位值）。示教时按 △ 可以把
 *      "当前三个角度"设成收纳姿态（掉电丢失，存 Flash 由 teach_save() 负责）。 */
void    arm_retract(void);

/* ---- 运行时可改的"收纳姿态"（示教用）---------------------------------
 * 默认 = POSE_STOW。示教时录到一个满意的收拢位置就 arm_set_stow() 存下来。
 * 为什么要可变：新机构的 POSE_STOW 是占位值，而"收拢"这个位置
 * 只能在实物上看着调，用改代码+重编译的方式太慢。 */
void    arm_set_stow(const Pose_t *p);
Pose_t  arm_get_stow(void);

/* ---- 夹持动作（单通道，旧接口，保留兼容）------------------------------ */
void    arm_open_grip(void);
void    arm_close_grip(void);

/* ---- 夹爪：0~100 开合量（上层代码统一用这一套）------------------------
 * pct: 0 = 全开，100 = 全合。超出范围会被夹紧。
 * ---------------------------------------------------------------------- */
void    grip_set(int16_t pct);        /* 设定开合量 0~100（缓动）*/
void    grip_open(void);              /* 全开 */
void    grip_close(void);             /* 全合 */
void    grip_toggle(void);            /* 开↔合 切换（手柄一键用）*/
int16_t grip_get(void);               /* 当前开合量 */
uint8_t grip_is_moving(void);         /* 夹爪还在动 → 1 */

void    servo_poll(void);                          /* 每轮主循环调用，50Hz */

#endif /* SERVO_H */
