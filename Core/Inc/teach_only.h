/*
teach_only.h —— 机械臂示教录制 / 回放（独立模块）

===============================================================================
这是一个**可以单独编译，也可以被别人的主循环调用**的模块。
===============================================================================

【两种用法】

  ① 独立跑（本工程现在就是这样）
        teach_only_main();              // 里面自带 while(1)

  ② 合并进底盘队员的主循环（推荐，车真正跑起来时用这个）
        // --- 你自己的初始化 ---
        dwt_init();
        ps2_init();
        motor_init();                   // 底盘
        teach_only_init();              // 舵机 + 从 Flash 读回录制

        // --- 你自己的主循环，20ms 一圈 ---
        while (1)
        {
            ps2_poll();                 // ★ 手柄由主循环统一读一次
            mecanum_drive(vx, vy, w);   // 底盘自己干活
            teach_only_poll();          // ★ 机械臂示教，每圈调一次
            while (HAL_GetTick() - last < 20) {}
            last = HAL_GetTick();
        }

【边界划分 —— 为什么这么切】

  | 资源 | 归谁 | 说明 |
  |---|---|---|
  | TIM1 / TIM2 / TIM3 | 底盘 | 8 路电机 PWM，本模块**完全不碰** |
  | TIM4 | 机械臂 | PB6/PB7/PB8 三路 50Hz 舵机 |
  | PA4~PA7（PS2 时序）| 双方共用 | **由主循环调一次 `ps2_poll()`**，本模块只读结果 |
  | 两个摇杆 | **底盘** | 本模块**一个摇杆都不读** |
  | 十字键 / L1 R1 L2 R2 / △○×□ | 机械臂 | 本模块独占这些按键 |
  | SELECT / START | 机械臂 | 录制 / 回放 |
  | PA13 / PA14 | SWD | 谁都别占 |
  | Flash 最后 2 页 | 机械臂 | 录制数据，0x0800F800 |
===============================================================================
*/
#ifndef TEACH_ONLY_H
#define TEACH_ONLY_H

#include <stdint.h>

/* 独立跑：里面自带 while(1)，不会返回 */
void teach_only_main(void);

/* 合并用：上电调一次 */
void teach_only_init(void);

/* 合并用：主循环里每 20ms 调一次。前提是调用方已经调过 ps2_poll() */
void teach_only_poll(void);

/* ---------------------------------------------------------------------------
 * ★ 给底盘留的钩子：存 Flash 之前会被调用一次
 *
 * 为什么要留这个：
 *   写 Flash 时 HAL 会关中断 100~200ms。舵机 PWM 是硬件在发，不受影响；
 *   **但电机 PWM 也是硬件在发 —— 会保持最后的速度冲出去 200ms。**
 *
 * 底盘那边只要在自己的代码里定义同名函数（不带 __weak 就能覆盖），
 * 链接时会自动用你们的版本：
 *
 *      void teach_before_save(void)
 *      {
 *          mecanum_drive(0, 0, 0);       // 停车
 *      }
 *
 * 不定义也没关系，这里是空实现。
 * ------------------------------------------------------------------------- */
void teach_before_save(void);

#endif /* TEACH_ONLY_H */
