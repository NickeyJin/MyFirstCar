/*
 * diag.h —— 开发期排查代码的开关（正常跑车时两个都是 0）
 *
 * 这两个模式都是"上电即进、永不返回"，专门用来把"轮子不转"拆开定位。
 * 正常跑车保持 0 就行 —— 这时 diag.c 里的函数一个都不会被编译进去，
 * 既不占 flash 也不占时间。要排查就改回 1 重新编译。
 *
 * 两个都开时 APP_RR_TEST 先生效。
 *
 * ===================================================================
 * 【APP_DIAG_MODE】占空比 / 频率对比测试
 *
 * 上电后无限循环跑三段，每段先闪灯报段号，再同时驱动四个轮子：
 *     闪 1 → 定时器 PWM 20kHz，占空比 80%
 *     闪 2 → GPIO 直推 100Hz 方波，占空比 40%
 *     闪 3 → 定时器 PWM 1kHz，占空比 80%
 *
 * 2026-10-11 实测：三段全转，速度 闪3 > 闪2 > 闪1。
 *   ⇒ 不是频率问题（20kHz 也能转），是占空比问题：这颗电机启动电压偏高，
 *     40% 带不动；同时驱动板有开关损耗，频率越高有效占空比越低。
 *   ⇒ 正式代码已改成 PSC=71 / ARR=999 → 1kHz，见 motor.h 的 MOTOR_PWM_ARR。
 *
 * ===================================================================
 * 【APP_RR_TEST】右后轮专项排查
 *
 * 上电后只驱动右后轮，循环跑四段，每段 3 秒，靠闪灯报段号：
 *     闪 1 → PA11 当普通 GPIO 直接拉高（IN2=3.3V, IN1=0）   期望：前进
 *     闪 2 → PA8  当普通 GPIO 直接拉高（IN1=3.3V, IN2=0）   期望：后退
 *     闪 3 → PA11 走 TIM1_CH4 的 PWM（100%）                期望：前进
 *     闪 4 → PA8  走 TIM1_CH1 的 PWM（100%）                期望：后退
 * 每段之间两路都拉低 = 高阻滑行，然后停 1.5 秒。
 *
 * 2026-10-11 实测：闪 1、闪 3 不动，闪 2、闪 4 正常转 ⇒ 问题在 PA11 这一侧。
 * PCB 已经把 PA11 → DRV8833 IN2 画死，不能改线，所以代码保持 PA11。
 *
 * ！！这个测试**区分不了**下面两种情况，它们看起来一模一样（都是"这一段不动"）：
 *     ① PA11 真的没有输出（MCU 脚 / PCB 走线 / 焊点 / DRV8833 输入脚）；
 *     ② 脚有输出，但这个轮子在"前进"这个机械方向上转不动（减速箱打滑 / 卡死）。
 *   区分办法一：万用表直流档，红笔点该脚排针、黑笔点 GND，在"闪 1"的 3 秒窗口里
 *               量 —— 3.3V ⇒ 脚是好的、锅在电机/减速箱；0V ⇒ 脚真没输出。
 *   区分办法二：把该片 DRV8833 的 OUT1/OUT2（到电机的两根线）对调再跑一遍 ——
 *               不动的那段从闪 1 变成闪 2 ⇒ 轮子的方向性机械故障；
 *               还是闪 1 不动 ⇒ PA11 / IN2 侧。
 *
 * 怎么读结果：
 *   1 和 2 都转   → 两个半桥都通、PA8/PA11 两个脚都好 → 不是电气问题，是机械阻力
 *   1 不转、2 转  → PA11 → DRV8833 IN2 这条路断了
 *   1 转、2 不转  → PA8 → DRV8833 IN1 那条路断了
 *   1 转、3 不转  → GPIO 能推动，但定时器 CH4 出不来波形（软件问题）
 *   1 不转、3 转  → 反过来，GPIO 那条路的问题
 *   全都不转      → 那片 DRV8833 坏了，或者 IN1/IN2 接反/接到别处了
 *
 * 这一段刻意绕开 motor_set()，所以不受 invert 影响，"MCU 脚 → 电机方向"直接对应。
 */
#ifndef DIAG_H
#define DIAG_H

#define APP_DIAG_MODE   0
#define APP_RR_TEST     0

void diag_run(void);        /* PWM 对比测试，永不返回 */
void diag_rr_run(void);     /* 右后轮专项测试，永不返回 */

#endif /* DIAG_H */
